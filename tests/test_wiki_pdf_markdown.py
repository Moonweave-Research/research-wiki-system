def test_docling_provider_uses_document_converter(monkeypatch, tmp_path: Path) -> None:
    pdf = tmp_path / "paper.pdf"
    pdf.write_bytes(b"%PDF")

    class FakeDocument:
        def export_to_markdown(self) -> str:
            return "# Docling\n\nConverted markdown."

    class FakeResult:
        document = FakeDocument()

    class FakeConverter:
        def convert(self, source: str) -> FakeResult:
            assert source == str(pdf)
            return FakeResult()

    class FakeModule:
        DocumentConverter = FakeConverter

    monkeypatch.setattr(
        markdown_mod.importlib,
        "import_module",
        lambda name: FakeModule if name == "docling.document_converter" else None,
    )

    extraction = markdown_mod.provider_extractor("docling")(pdf)

    assert extraction.extractor == "docling"
    assert extraction.markdown == "# Docling\n\nConverted markdown."


def test_pymupdf4llm_provider_disables_ocr_by_default(monkeypatch, tmp_path: Path) -> None:
    pdf = tmp_path / "paper.pdf"
    pdf.write_bytes(b"%PDF")
    calls: list[dict] = []

    class FakeModule:
        @staticmethod
        def to_markdown(source: str, **kwargs) -> str:
            calls.append({"source": source, **kwargs})
            return "# PyMuPDF4LLM"

    monkeypatch.setattr(
        markdown_mod.importlib,
        "import_module",
        lambda name: FakeModule if name == "pymupdf4llm" else None,
    )

    extraction = markdown_mod.provider_extractor("pymupdf4llm")(pdf)

    assert extraction.extractor == "pymupdf4llm"
    assert calls == [{"source": str(pdf), "use_ocr": False}]


