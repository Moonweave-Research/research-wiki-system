def write_note(path: Path, *, alias: str, pdf_path: str = "") -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        f"""---
aliases: [{alias}]
domain: research
category: materials
tags: []
sources: []
pdf_path: {pdf_path}
---
# {alias}

## Abstract
Some abstract.
""",
        encoding="utf-8",
    )


def read_jsonl(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines()]


def test_build_pdf_markdown_cache_writes_markdown_and_manifest(tmp_path: Path) -> None:
    wiki = tmp_path / "wiki"
    output_dir = tmp_path / ".graph_index" / "pdf_markdown"
    manifest = tmp_path / ".graph_index" / "pdf_markdown_manifest.jsonl"
    readable_pdf = tmp_path / "readable.pdf"
    readable_pdf.write_bytes(b"%PDF-1.4 readable")
    missing_pdf = tmp_path / "missing.pdf"
    write_note(wiki / "research" / "readable.md", alias="Readable", pdf_path=str(readable_pdf))
    write_note(wiki / "research" / "missing.md", alias="Missing", pdf_path=str(missing_pdf))
    write_note(wiki / "research" / "no_pdf.md", alias="No PDF", pdf_path="")

    def extract(path: Path) -> MarkdownExtraction:
        assert path == readable_pdf
        return MarkdownExtraction(
            markdown="## Abstract\n\nCached markdown.\n\n## Methods\n\nProcedure.",
            page_count=4,
            warnings=["layout fallback"],
            extractor="fake",
        )

    report = build_pdf_markdown_cache(
        wiki,
        output_dir=output_dir,
        manifest_path=manifest,
        extract_markdown=extract,
    )

    assert report["summary"] == {
        "papers": 3,
        "cached": 1,
        "skipped": 2,
        "missing_pdfs": 1,
        "extraction_errors": 0,
    }
    markdown_file = output_dir / "readable.md"
    assert markdown_file.exists()
    markdown = markdown_file.read_text(encoding="utf-8")
    assert markdown.startswith("<!-- generated by scripts.ingest.wiki_pdf_markdown")
    assert "## Abstract" in markdown
    assert "Cached markdown." in markdown

    rows = read_jsonl(manifest)
    assert [row["paper_id"] for row in rows] == [
        "paper:missing",
        "paper:no_pdf",
        "paper:readable",
    ]
    readable = rows[2]
    assert readable["cached"] is True
    assert readable["markdown_path"] == str(markdown_file)
    assert readable["pdf_size"] == readable_pdf.stat().st_size
    assert readable["pdf_sha256"] == hashlib.sha256(readable_pdf.read_bytes()).hexdigest()
    assert readable["markdown_chars"] == len(markdown.strip())
    assert readable["page_count"] == 4
    assert readable["extractor"] == "fake"
    assert readable["section_headings"] == ["Abstract", "Methods"]
    assert readable["warnings"] == ["layout fallback"]


def test_pdf_markdown_incremental_skips_unchanged_hash(tmp_path: Path) -> None:
    wiki = tmp_path / "wiki"
    output_dir = tmp_path / "pdf_markdown"
