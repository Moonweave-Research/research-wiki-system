def test_dry_run_is_default_and_writes_nothing(tmp_path: Path, capsys) -> None:
    vault = tmp_path / "wiki"
    db = tmp_path / "linkgraph.sqlite"
    _write_paper(vault, "paperSpecific2024", ["Liquid Crystal", "Elastomer"])
    _write_concept(vault, "Elastomer", ["Elastomer"], "# Elastomer\n\n## 정의\n\nHand body.\n")
    _write_concept(
        vault,
        "Liquid_Crystal",
        ["Liquid Crystal"],
        "# Liquid Crystal\n\n## 정의\n\nHand body.\n",
    )
    specific = _write_concept(
        vault,
        "Liquid_Crystal_Elastomer",
        ["LCE", "Liquid Crystal Elastomers"],
        "# Liquid Crystal Elastomer\n\n## 정의\n\nHand body.\n",
    )
    before = specific.read_text(encoding="utf-8")
    _build_db(vault, db)

    result = concept_split.main(
        [
            "--vault",
            str(vault),
            "--db",
            str(db),
            "--min-papers",
            "1",
            "--backfill-min-papers",
            "1",
        ]
    )

    assert result == 0
    assert specific.read_text(encoding="utf-8") == before
    output = capsys.readouterr().out
    assert "UPDATE concepts/Liquid_Crystal_Elastomer.md" in output
    assert "concept split dry-run" in output


