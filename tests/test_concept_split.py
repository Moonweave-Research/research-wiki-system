def test_apply_routes_specific_concept_and_suppresses_broad_parent_auto_links(
    tmp_path: Path,
) -> None:
    vault = tmp_path / "wiki"
    db = tmp_path / "linkgraph.sqlite"
    _write_paper(vault, "paperSpecific2024", ["Dielectric", "Elastomer", "Actuator"])
    _write_paper(vault, "paperBroad2024", ["Actuator"])
    _write_paper(vault, "paperManual2024", ["Actuator"])
    actuator = _write_concept(
        vault,
        "Actuator",
        ["Actuator"],
        "# Actuator\n\n## 정의\n\nHand body.\n\n"
        "- Hand curated paper: [[paperManual2024]]\n\n"
        "<!-- concept-backfill:start -->\n"
        "## 관련 논문 (자동 생성)\n\n"
        "<!-- Regenerated by scripts.ingest.concept_backfill. -->\n"
        "- [[stalePaper]]\n"
        "- [[paperSpecific2024]]\n"
        "<!-- concept-backfill:end -->\n",
    )
    _write_concept(vault, "Elastomer", ["Elastomer"], "# Elastomer\n\n## 정의\n\nHand body.\n")
    _write_concept(vault, "Dielectric", ["Dielectric"], "# Dielectric\n\n## 정의\n\nHand body.\n")
    specific = _write_concept(
        vault,
        "Dielectric_Elastomer_Actuator",
        ["DEA", "Dielectric Elastomer"],
        "# Dielectric Elastomer Actuator\n\n## 정의\n\nHand body.\n",
    )
    _build_db(vault, db)

    result = concept_split.main(
        [
            "--vault",
            str(vault),
            "--db",
            str(db),
            "--min-papers",
            "1",
            "--backfill-min-papers",
            "1",
            "--apply",
        ]
    )
    first_pass = {
        path.relative_to(vault).as_posix(): path.read_text(encoding="utf-8")
        for path in sorted((vault / "concepts").glob("*.md"))
    }
    result_second = concept_split.main(
        [
            "--vault",
            str(vault),
            "--db",
            str(db),
            "--min-papers",
            "1",
            "--backfill-min-papers",
            "1",
            "--apply",
        ]
    )

    assert result == 0
    assert result_second == 0
    assert {
        path.relative_to(vault).as_posix(): path.read_text(encoding="utf-8")
        for path in sorted((vault / "concepts").glob("*.md"))
    } == first_pass

    actuator_text = actuator.read_text(encoding="utf-8")
    assert "## 정의\n\nHand body.\n\n" in actuator_text
    assert "- Hand curated paper: [[paperManual2024]]\n" in actuator_text
    assert actuator_text.count("[[paperManual2024]]") == 1
    assert "- [[paperBroad2024]]\n" in actuator_text
    assert "stalePaper" not in actuator_text
    assert "- [[paperSpecific2024]]\n" not in actuator_text

    specific_text = specific.read_text(encoding="utf-8")
    assert "- [[paperSpecific2024]]\n" in specific_text
    assert "- [[paperBroad2024]]\n" not in specific_text


