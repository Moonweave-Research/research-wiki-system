from pathlib import Path

import yaml

from scripts.core import linkgraph
from scripts.ingest import concept_routing, concept_split


def _write_paper(vault: Path, stem: str, tags: list[str]) -> None:
    path = vault / "research" / f"{stem}.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    frontmatter = {
        "aliases": [stem],
        "domain": "research",
        "category": "materials",
        "tags": tags,
        "sources": [],
    }
    path.write_text(
        "---\n"
        + yaml.safe_dump(frontmatter, sort_keys=False, allow_unicode=True)
        + "---\n"
        + f"# {stem}\n\nNo hand-authored wikilinks here.\n",
        encoding="utf-8",
    )


def _write_concept(vault: Path, stem: str, aliases: list[str], body: str) -> Path:
    path = vault / "concepts" / f"{stem}.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    frontmatter = {
        "aliases": aliases,
        "domain": "research",
        "category": "concepts",
        "tags": aliases[:1] or [stem.replace("_", " ")],
        "sources": [],
    }
    path.write_text(
        "---\n"
        + yaml.safe_dump(frontmatter, sort_keys=False, allow_unicode=True)
        + "---\n"
        + body,
        encoding="utf-8",
    )
    return path


def _build_db(vault: Path, db: Path) -> None:
    linkgraph.build_index(vault, db)


