def _split_words(value: str) -> list[str]:
    return [part for part in re.split(r"[\s_\-/]+", value.casefold().strip()) if part]


def _singularize_word(word: str) -> str:
    if len(word) > 4 and word.endswith("ies"):
        return word[:-3] + "y"
    if len(word) > 3 and word.endswith("s") and not word.endswith("ss"):
        return word[:-1]
    return word


def _join_words(words: list[str]) -> str:
    return re.sub(r"[^0-9a-z가-힣]+", "", "".join(words), flags=re.IGNORECASE)


def normalized_variants(value: str) -> list[str]:
    words = _split_words(value)
    if not words:
        return []
    variants = [_join_words(words)]
    singular_words = [*words[:-1], _singularize_word(words[-1])]
    singular = _join_words(singular_words)
    if singular not in variants:
        variants.append(singular)
    return variants


def canonical_key(value: str) -> str:
    variants = normalized_variants(value)
    return variants[-1] if variants else ""


def slugify_tag(tag: str) -> str:
    slug = re.sub(r"[\s\-]+", "_", tag.strip())
    slug = re.sub(r"[^\w가-힣]+", "", slug, flags=re.UNICODE)
    slug = re.sub(r"_+", "_", slug).strip("_")
    return slug or "Concept"


def _frontmatter(text: str) -> dict:
    match = re.match(r"^---\r?\n(.*?)\r?\n---(?:\r?\n|$)", text, re.DOTALL)
    if not match:
        return {}
    loaded = yaml.safe_load(match.group(1))
    return loaded if isinstance(loaded, dict) else {}


def _as_list(value: object) -> list[str]:
    if value is None:
        return []
    if isinstance(value, list):
        return [str(item) for item in value]
    return [str(value)]


def load_concept_index(vault_dir: Path) -> dict[str, ExistingConcept]:
    concepts_dir = vault_dir / "concepts"
    index: dict[str, ExistingConcept] = {}
    if not concepts_dir.exists():
        return index
    for path in sorted(concepts_dir.glob("*.md")):
        rel_path = path.relative_to(vault_dir).as_posix()
        concept = ExistingConcept(path=path, rel_path=rel_path)
        text = path.read_text(encoding="utf-8")
        labels = [path.stem, *_as_list(_frontmatter(text).get("aliases"))]
        for label in labels:
            for variant in normalized_variants(label):
                index.setdefault(variant, concept)
    return index


def find_concept(tag: str, concept_index: dict[str, ExistingConcept]) -> ExistingConcept | None:
    for variant in normalized_variants(tag):
        if variant in concept_index:
            return concept_index[variant]
    return None


def load_tag_papers(db_path: Path) -> list[TagPapers]:
    conn = sqlite3.connect(db_path)
    try:
        grouped: dict[str, set[str]] = defaultdict(set)
        for tag, note_path in conn.execute(
            """
            SELECT tags.tag, tags.note_path
            FROM tags
            JOIN notes ON notes.path = tags.note_path
            WHERE tags.note_path LIKE 'research/%'
              AND COALESCE(notes.status, '') != 'irrelevant'
            """
        ):
            tag_text = str(tag)
            if tag_text.casefold() in SKIPPED_TAGS:
                continue
            grouped[tag_text].add(str(note_path))
    finally:
        conn.close()
    return sorted(
        (TagPapers(tag=tag, papers=papers) for tag, papers in grouped.items()),
        key=lambda item: (-len(item.papers), item.tag.casefold()),
    )


def load_qualifying_tags(db_path: Path, min_papers: int) -> list[TagPapers]:
    return [item for item in load_tag_papers(db_path) if len(item.papers) >= min_papers]


def _append_unique(values: list[str], value: str) -> None:
    seen = {item.casefold() for item in values}
    if value.casefold() not in seen:
        values.append(value)


def _split_display_words(value: str) -> list[str]:
    return [part for part in re.split(r"[\s_\-/]+", value.strip()) if part]


def singular_display_title(value: str) -> str:
    words = _split_display_words(value)
    if not words:
        return value
    words[-1] = _singularize_word(words[-1].casefold())
    return " ".join(words).title()


def definition_for(title: str) -> str | None:
    if title in DEFINITIONS:
        return DEFINITIONS[title]
    return DEFINITIONS.get(singular_display_title(title))


def _paper_stems(paths: set[str]) -> set[str]:
    return {Path(path).stem for path in paths}


def _paper_tag_keys(tag_papers: list[TagPapers]) -> dict[str, set[str]]:
    by_paper: dict[str, set[str]] = defaultdict(set)
    for item in tag_papers:
        variants = normalized_variants(item.tag)
        for paper in item.papers:
            by_paper[paper].update(variants)
    return dict(by_paper)


def _tag_papers_by_key(tag_papers: list[TagPapers]) -> dict[str, set[str]]:
    by_key: dict[str, set[str]] = defaultdict(set)
    for item in tag_papers:
        for variant in normalized_variants(item.tag):
            by_key[variant].update(item.papers)
    return dict(by_key)


def _required_tag_groups(rule: SplitRule) -> list[tuple[str, ...]]:
    groups: list[tuple[str, ...]] = []
    for index, tag in enumerate(rule.required_tags):
        aliases = rule.required_tag_aliases[index] if index < len(rule.required_tag_aliases) else ()
        groups.append((tag, *aliases))
    return groups


def _paper_matches_rule(paper_keys: set[str], rule: SplitRule) -> bool:
    for group in _required_tag_groups(rule):
        group_keys = {variant for tag in group for variant in normalized_variants(tag)}
        if not paper_keys.intersection(group_keys):
            return False
    return True


def _rule_scope_keys(rule: SplitRule) -> set[str]:
    labels = (*rule.required_tags, *rule.suppressed_parent_slugs, rule.target_title, *rule.aliases)
    return {variant for label in labels for variant in normalized_variants(label)}


def _rule_required_keys(rule: SplitRule) -> set[str]:
    return {
        variant
        for group in _required_tag_groups(rule)
        for label in group
        for variant in normalized_variants(label)
    }


def _rule_subsumes(more_specific: SplitRule, less_specific: SplitRule) -> bool:
    return _rule_required_keys(less_specific).issubset(_rule_scope_keys(more_specific))


def _target_concept(
    rule: SplitRule, concept_index: dict[str, ExistingConcept]
) -> ExistingConcept | None:
    for label in (rule.target_slug, rule.target_title, *rule.aliases):
        matched = find_concept(label, concept_index)
        if matched is not None:
            return matched
    return None


def _parent_rel_path(parent_slug: str, concept_index: dict[str, ExistingConcept]) -> str:
    matched = find_concept(parent_slug, concept_index)
    if matched is not None:
        return matched.rel_path
    return f"concepts/{slugify_tag(parent_slug)}.md"


def _new_split_plan(vault_dir: Path, rule: SplitRule, qualifying: set[str]) -> ConceptPlan:
    aliases = list(rule.aliases) or [rule.target_title]
    _append_unique(aliases, rule.target_title)
    rel_path = f"concepts/{rule.target_slug}.md"
    return ConceptPlan(
        path=vault_dir / rel_path,
        rel_path=rel_path,
        title=rule.target_title,
        aliases=aliases,
        primary_tag=rule.target_title,
        paper_stems=_paper_stems(qualifying),
        create=True,
        definition=rule.definition,
    )


def route_papers_to_concepts(
    vault_dir: Path,
    tag_papers: list[TagPapers],
    *,
    rules: tuple[SplitRule, ...] | list[SplitRule] = SPLIT_RULES,
    min_papers: int | None = None,
) -> RoutingResult:
    concept_index = load_concept_index(vault_dir)
    paper_keys = _paper_tag_keys(tag_papers)
    rule_counts: dict[str, int] = {}
    plans_by_rel_path: dict[str, ConceptPlan] = {}
    suppressed: dict[str, set[str]] = defaultdict(set)
    skipped_rules: list[str] = []
    accepted_rules: list[tuple[SplitRule, set[str]]] = []

    sorted_rules = sorted(
        rules,
        key=lambda rule: (-len(rule.required_tags), rule.target_slug.casefold()),
    )
    for rule in sorted_rules:
        qualifying = {
            paper for paper, keys in paper_keys.items() if _paper_matches_rule(keys, rule)
        }
        for accepted_rule, accepted_papers in accepted_rules:
            if _rule_subsumes(accepted_rule, rule):
                qualifying -= accepted_papers
        rule_counts[rule.target_slug] = len(qualifying)
        threshold = min_papers if min_papers is not None else rule.min_papers
        if len(qualifying) < threshold:
            continue

        existing = _target_concept(rule, concept_index)
        if existing is None and (not rule.create_if_missing or not rule.definition):
            skipped_rules.append(rule.target_slug)
            continue

        if existing is None:
            plan = _new_split_plan(vault_dir, rule, qualifying)
        else:
            plan = ConceptPlan(
                path=existing.path,
                rel_path=existing.rel_path,
                title=existing.path.stem.replace("_", " "),
                aliases=[],
                primary_tag=rule.target_title,
                paper_stems=_paper_stems(qualifying),
                create=False,
                definition=rule.definition,
            )
        if existing_plan := plans_by_rel_path.get(plan.rel_path):
            existing_plan.paper_stems.update(plan.paper_stems)
        else:
            plans_by_rel_path[plan.rel_path] = plan
        accepted_rules.append((rule, qualifying))
        for parent_slug in rule.suppressed_parent_slugs:
            suppressed[_parent_rel_path(parent_slug, concept_index)].update(qualifying)

    return RoutingResult(
        specific_plans=sorted(plans_by_rel_path.values(), key=lambda plan: plan.rel_path),
        suppressed_papers_by_parent=dict(sorted(suppressed.items())),
        skipped_rules=sorted(skipped_rules, key=str.casefold),
        qualifying_counts=rule_counts,
    )


def plan_tag_backfill(
    vault_dir: Path,
    tag_papers: list[TagPapers],
    *,
    suppressed_papers_by_parent: dict[str, set[str]] | None = None,
    skip_rel_paths: set[str] | None = None,
    skip_missing_definitions: bool = False,
) -> BackfillResult:
    concept_index = load_concept_index(vault_dir)
    plans_by_rel_path: dict[str, ConceptPlan] = {}
    new_plans_by_key: dict[str, ConceptPlan] = {}
    skipped_tags: list[str] = []
    suppressed = suppressed_papers_by_parent or {}
    skipped_paths = skip_rel_paths or set()

    for item in tag_papers:
        matched = find_concept(item.tag, concept_index)
        if matched is not None:
            if matched.rel_path in skipped_paths:
                continue
            plan = plans_by_rel_path.setdefault(
                matched.rel_path,
                ConceptPlan(
                    path=matched.path,
                    rel_path=matched.rel_path,
                    title=matched.path.stem.replace("_", " "),
                    aliases=[],
                    primary_tag=item.tag,
                    create=False,
                ),
            )
        else:
            if skip_missing_definitions and definition_for(item.tag) is None:
                skipped_tags.append(item.tag)
                continue
            key = canonical_key(item.tag)
            if key not in new_plans_by_key:
                slug = slugify_tag(item.tag)
                rel_path = f"concepts/{slug}.md"
                plan = ConceptPlan(
                    path=vault_dir / rel_path,
                    rel_path=rel_path,
                    title=item.tag,
                    aliases=[item.tag],
                    primary_tag=item.tag,
                    create=True,
                )
                new_plans_by_key[key] = plan
                plans_by_rel_path[rel_path] = plan
            plan = new_plans_by_key[key]
            _append_unique(plan.aliases, item.tag)

        paper_paths = set(item.papers) - suppressed.get(plan.rel_path, set())
        plan.paper_stems.update(_paper_stems(paper_paths))

    return BackfillResult(
        plans=sorted(plans_by_rel_path.values(), key=lambda plan: plan.rel_path),
        skipped_tags=sorted(skipped_tags, key=str.casefold),
    )


def build_plan(vault_dir: Path, tag_papers: list[TagPapers]) -> list[ConceptPlan]:
    return plan_tag_backfill(vault_dir, tag_papers).plans


def render_auto_section(paper_stems: set[str]) -> str:
    lines = [AUTO_START, AUTO_HEADING, "", AUTO_NOTE]
    lines.extend(f"- [[{stem}]]" for stem in sorted(paper_stems, key=str.casefold))
    lines.append(AUTO_END)
    return "\n".join(lines) + "\n"


def _wikilink_targets(text: str) -> set[str]:
    targets = set(re.findall(r"\[\[([^\]|#]+)(?:[#|][^\]]*)?\]\]", text))
    return targets | {Path(target).stem for target in targets}


def _without_auto_section(text: str) -> str:
    start_count = text.count(AUTO_START)
    end_count = text.count(AUTO_END)
    if start_count != end_count or start_count > 1:
        raise ValueError("invalid concept-backfill auto section markers")
    if start_count == 0:
        return text
    start = text.find(AUTO_START)
    end = text.find(AUTO_END)
    return text[:start] + text[end + len(AUTO_END) :]


def replace_auto_section(text: str, paper_stems: set[str]) -> str:
    hand_linked = _wikilink_targets(_without_auto_section(text))
    section = render_auto_section(paper_stems - hand_linked)
    start = text.find(AUTO_START)
    end = text.find(AUTO_END)
    if start >= 0 and end >= start:
        end += len(AUTO_END)
        return text[:start].rstrip() + "\n\n" + section + text[end:].lstrip("\n")
    return text.rstrip() + "\n\n" + section


def render_new_concept(plan: ConceptPlan) -> str:
    definition = plan.definition or definition_for(plan.title)
    if definition is None:
        raise ValueError(f"No curated definition for new concept tag: {plan.title}")
    frontmatter = {
        "aliases": plan.aliases or [plan.title],
        "domain": "research",
        "category": "concepts",
        "tags": [plan.primary_tag],
        "sources": [],
    }
    return (
        "---\n"
        + yaml.safe_dump(frontmatter, sort_keys=False, allow_unicode=True)
        + "---\n"
        + f"# {plan.title}\n\n"
        + "## 정의\n\n"
        + definition
        + "\n\n"
        + render_auto_section(plan.paper_stems)
    )


def apply_plan(plans: list[ConceptPlan], *, apply: bool, label: str) -> int:
    rendered: list[tuple[ConceptPlan, str, str | None, str]] = []
    for plan in plans:
        if plan.create:
            next_text = render_new_concept(plan)
            action = "CREATE"
            current_text = plan.path.read_text(encoding="utf-8") if plan.path.exists() else None
        else:
            current_text = plan.path.read_text(encoding="utf-8")
            next_text = replace_auto_section(current_text, plan.paper_stems)
            action = "UPDATE"
        if current_text == next_text:
            continue
        rendered.append((plan, action, current_text, next_text))

    changed = 0
    for plan, action, _current_text, next_text in rendered:
        print(f"{action} {plan.rel_path} ({len(plan.paper_stems)} papers)")
        changed += 1
        if apply:
            plan.path.parent.mkdir(parents=True, exist_ok=True)
            plan.path.write_text(next_text, encoding="utf-8")
    mode = "applied" if apply else "dry-run"
    noun = "changed" if apply else "would change"
    print(f"{label} {mode}: {changed} file(s) {noun}")
    return changed


def parent_backfill_plans(
    vault_dir: Path,
    tag_papers: list[TagPapers],
    suppressed_papers_by_parent: dict[str, set[str]],
    *,
    min_papers: int = 20,
) -> list[ConceptPlan]:
    concept_index = load_concept_index(vault_dir)
    qualifying = [item for item in tag_papers if len(item.papers) >= min_papers]
    papers_by_tag_key = _tag_papers_by_key(qualifying)
    plans: list[ConceptPlan] = []
    for rel_path, suppressed in sorted(suppressed_papers_by_parent.items()):
        path = vault_dir / rel_path
        if not path.exists():
            continue
        tag_label = Path(rel_path).stem
        matched = find_concept(tag_label, concept_index)
        if matched is not None:
            tag_label = matched.path.stem
        paper_paths: set[str] = set()
        for variant in normalized_variants(tag_label):
            paper_paths.update(papers_by_tag_key.get(variant, set()))
        if not paper_paths:
            continue
        paper_paths -= suppressed
        plans.append(
            ConceptPlan(
                path=path,
                rel_path=rel_path,
                title=Path(rel_path).stem.replace("_", " "),
                aliases=[],
                primary_tag=tag_label.replace("_", " "),
                paper_stems=_paper_stems(paper_paths),
                create=False,
            )
        )
    return plans
